// Lingua del sito: cookie scelto dall'utente, altrimenti Accept-Language del browser.
export async function getLocale(): Promise<Locale> {
  const fromCookie = (await cookies()).get(LOCALE_COOKIE)?.value;
  if (fromCookie === "it" || fromCookie === "en") return fromCookie;
  const accept = (await headers()).get("accept-language") ?? "";
  return accept.toLowerCase().startsWith("it") ? "it" : accept ? "en" : "it";
}

